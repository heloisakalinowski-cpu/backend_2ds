export function filme(nome, dataAluguel)
{
    return `O filme ${nome} alugado em ${dataAluguel}.`
}
export function AlugarFilme(nome, dataAluguel)
{
    return `O filme ${nome} foi alugado em ${dataAluguel}.`
}
export function DevolverFilme(nome, dataDevolucao)
{
    return `O filme ${nome} foi devolvido em ${dataDevolucao}.`
}